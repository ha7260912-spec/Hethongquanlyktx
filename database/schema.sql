-- MySQL 8.0+. Chay tren schema trong, bang: python -m database.manage init --sample
CREATE TABLE Users (
 id INT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(50) NOT NULL UNIQUE,
 password VARCHAR(64) NOT NULL, role ENUM('admin','user') NOT NULL DEFAULT 'user', HoTen VARCHAR(100)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE SinhVien (
 MaSV VARCHAR(10) PRIMARY KEY, SoCMT VARCHAR(15) NOT NULL UNIQUE, HoTen VARCHAR(100) NOT NULL,
 NgaySinh DATE, Lop VARCHAR(20), QueQuan VARCHAR(200)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE Phong (
 SoPhong VARCHAR(10) PRIMARY KEY, LoaiPhong VARCHAR(50), DonGia DECIMAL(12,0) NOT NULL,
 SoNguoiToiDa INT NOT NULL, CHECK(DonGia>0), CHECK(SoNguoiToiDa>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE DangKyPhong (
 MaDK INT AUTO_INCREMENT PRIMARY KEY, MaSV VARCHAR(10) NOT NULL, SoPhong VARCHAR(10) NOT NULL,
 NgayBatDau DATE NOT NULL, NgayKetThuc DATE, DonGiaApDung DECIMAL(12,2) NOT NULL,
 FOREIGN KEY(MaSV) REFERENCES SinhVien(MaSV), FOREIGN KEY(SoPhong) REFERENCES Phong(SoPhong),
 INDEX ix_dkp_phong_time(SoPhong,NgayBatDau,NgayKetThuc),
 INDEX ix_dkp_sv_time(MaSV,NgayBatDau,NgayKetThuc),
 CHECK(NgayKetThuc IS NULL OR NgayKetThuc>=NgayBatDau), CHECK(DonGiaApDung>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE Khach (
 MaKhach INT AUTO_INCREMENT PRIMARY KEY, SoCMT VARCHAR(15) NOT NULL UNIQUE,
 Ten VARCHAR(100) NOT NULL, NgaySinh DATE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE Tham (
 MaTham INT AUTO_INCREMENT PRIMARY KEY, MaKhach INT NOT NULL, MaSV VARCHAR(10) NOT NULL,
 NgayDenChoi DATE NOT NULL, FOREIGN KEY(MaKhach) REFERENCES Khach(MaKhach),
 FOREIGN KEY(MaSV) REFERENCES SinhVien(MaSV), INDEX ix_tham_time(NgayDenChoi,MaSV,MaKhach)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE DichVu (
 MaDV VARCHAR(10) PRIMARY KEY, TenDV VARCHAR(100) NOT NULL, DonGia DECIMAL(12,2) NOT NULL,
 CHECK(DonGia>=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE SuDungDichVu (
 MaSD INT AUTO_INCREMENT PRIMARY KEY, MaSV VARCHAR(10) NOT NULL, MaDV VARCHAR(10) NOT NULL,
 ThoiGianSuDung DATETIME NOT NULL, SoLuong INT NOT NULL DEFAULT 1, DonGiaApDung DECIMAL(12,2) NOT NULL,
 FOREIGN KEY(MaSV) REFERENCES SinhVien(MaSV), FOREIGN KEY(MaDV) REFERENCES DichVu(MaDV),
 INDEX ix_sddv_time(ThoiGianSuDung,MaSV,MaDV), CHECK(SoLuong>0), CHECK(DonGiaApDung>=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE Xe (
 BienSo VARCHAR(15) PRIMARY KEY, MaSV VARCHAR(10) NOT NULL, LoaiXe VARCHAR(30), NgayDangKy DATE NOT NULL,
 FOREIGN KEY(MaSV) REFERENCES SinhVien(MaSV)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE DangKyXeThang (
 MaDKXe INT AUTO_INCREMENT PRIMARY KEY, MaSV VARCHAR(10) NOT NULL, BienSo VARCHAR(15) NOT NULL,
 KyThang DATE NOT NULL, DonGia DECIMAL(12,2) NOT NULL DEFAULT 100000,
 TrangThai ENUM('active','cancelled') NOT NULL DEFAULT 'active', NgayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_ve_bienso_thang(BienSo,KyThang),
 FOREIGN KEY(MaSV) REFERENCES SinhVien(MaSV), FOREIGN KEY(BienSo) REFERENCES Xe(BienSo),
 CHECK(DAY(KyThang)=1), CHECK(DonGia=100000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE LuotGuiXe (
 MaLuot INT AUTO_INCREMENT PRIMARY KEY, BienSo VARCHAR(15) NOT NULL, MaDKXe INT NOT NULL,
 ThoiGianLay DATETIME, ThoiGianGui DATETIME NOT NULL, SoTien DECIMAL(10,0) NOT NULL DEFAULT 0,
 FOREIGN KEY(BienSo) REFERENCES Xe(BienSo), FOREIGN KEY(MaDKXe) REFERENCES DangKyXeThang(MaDKXe),
 INDEX ix_lgx_vehicle_time(BienSo,ThoiGianGui,MaLuot),
 CHECK(ThoiGianLay IS NULL OR ThoiGianLay>=ThoiGianGui), CHECK(SoTien IN (0,3000))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE HoaDon (
 MaHD INT AUTO_INCREMENT PRIMARY KEY, MaSV VARCHAR(10) NOT NULL, KyThang DATE NOT NULL,
 TongTien DECIMAL(12,2) NOT NULL DEFAULT 0,
 TrangThai ENUM('unpaid','paid','overdue') NOT NULL DEFAULT 'unpaid',
 NgayLap DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, NgayThanhToan DATETIME, GhiChu VARCHAR(255),
 UNIQUE KEY uq_hoa_don_thang(MaSV,KyThang), FOREIGN KEY(MaSV) REFERENCES SinhVien(MaSV),
 CHECK(DAY(KyThang)=1), CHECK(TongTien>=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE ChiTietHoaDon (
 MaCT INT AUTO_INCREMENT PRIMARY KEY, MaHD INT NOT NULL, LoaiKhoan VARCHAR(30) NOT NULL,
 MoTa VARCHAR(255) NOT NULL, ThoiGian DATETIME, SoLuong DECIMAL(12,2) NOT NULL DEFAULT 1,
 DonGia DECIMAL(12,2) NOT NULL DEFAULT 0, ThanhTien DECIMAL(12,2) NOT NULL DEFAULT 0,
 FOREIGN KEY(MaHD) REFERENCES HoaDon(MaHD), CHECK(SoLuong>0), CHECK(DonGia>=0),
 CHECK(ThanhTien=SoLuong*DonGia)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
